#!/usr/bin/env bash
# SlowActionの仮モデル(箱の組み合わせ)を生成します。
#   実行: bash scripts/generate-slow-action-models.sh
# 単位はメートル、正面が+Z、上が+Y、キャラクターは足元が原点です。
# 面の頂点順は fpsBlock.obj と同じく cross(b-a, c-a) が外向き法線になる順です。
set -eu
out="$(dirname "$0")/../assets/model"

# 引数: 出力名  "材質名 r g b" ...  --  "材質名 cx cy cz hx hy hz" ...
make_model() {
	local name="$1"; shift
	{
		echo "# Generated by scripts/generate-slow-action-models.sh. Do not edit by hand."
		echo
		while [ "$1" != "--" ]; do
			set -- "$@"; local m=($1); shift
			printf 'newmtl %s\nKa 1.0 1.0 1.0\nKd %s %s %s\nKs 0.1 0.1 0.1\nNs 10\nd 1.0\n\n' "${m[0]}" "${m[1]}" "${m[2]}" "${m[3]}"
		done
	} > "$out/$name.mtl"
	shift
	printf '%s\n' "$@" | awk -v mtl="$name.mtl" '
	function quad(ax,ay,az, bx,by,bz, cx,cy,cz, dx,dy,dz, nx,ny,nz,   i) {
		v[++nv] = ax " " ay " " az; v[++nv] = bx " " by " " bz
		v[++nv] = cx " " cy " " cz; v[++nv] = dx " " dy " " dz
		for (i = 0; i < 4; i++) n[nv - i] = nx " " ny " " nz
		faces[cur] = faces[cur] sprintf("f %d/1/%d %d/1/%d %d/1/%d %d/1/%d\n", nv-3,nv-3, nv-2,nv-2, nv-1,nv-1, nv,nv)
	}
	{
		cur = $1; if (!(cur in faces)) order[++nm] = cur
		x0=$2-$5; x1=$2+$5; y0=$3-$6; y1=$3+$6; z0=$4-$7; z1=$4+$7
		if ($8 == "top") { quad(x0,y1,z1, x1,y1,z1, x1,y1,z0, x0,y1,z0, 0,1,0); next }
		quad(x0,y0,z1, x0,y1,z1, x0,y1,z0, x0,y0,z0, -1,0,0)
		quad(x1,y0,z0, x1,y1,z0, x1,y1,z1, x1,y0,z1, 1,0,0)
		quad(x0,y0,z0, x1,y0,z0, x1,y0,z1, x0,y0,z1, 0,-1,0)
		quad(x0,y1,z1, x1,y1,z1, x1,y1,z0, x0,y1,z0, 0,1,0)
		quad(x0,y1,z0, x1,y1,z0, x1,y0,z0, x0,y0,z0, 0,0,-1)
		quad(x0,y0,z1, x1,y0,z1, x1,y1,z1, x0,y1,z1, 0,0,1)
	}
	END {
		print "# Generated by scripts/generate-slow-action-models.sh. Do not edit by hand."
		print "mtllib " mtl
		for (i = 1; i <= nv; i++) print "v " v[i]
		print "vt 0 0"
		for (i = 1; i <= nv; i++) print "vn " n[i]
		for (i = 1; i <= nm; i++) { print "usemtl " order[i]; printf "%s", faces[order[i]] }
	}' > "$out/$name.obj"
}

