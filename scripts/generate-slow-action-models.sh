# 40m四方の床です。2mの敷石を明るさだけ少し変えた市松にして、移動速度を目で追えるようにします。
tiles=()
for ix in $(seq 0 19); do
	for iz in $(seq 0 19); do
		if [ $(( (ix + iz) % 2 )) -eq 0 ]; then m=TileA; else m=TileB; fi
		tiles+=("$m $((ix * 2 - 19)) -0.5 $((iz * 2 - 19)) 1 0.5 1 top")
	done
done
