// ---- マズルフラッシュ ----
// 銃口を原点に+Zへ伸びる炎です。正面から見える星形と、横から見える交差した3枚の炎を重ねます。
// 加算合成で光らせるので、色は明るさそのものです。
const flash = new ModelBuilder({
	FlashOuter: { kd: [1.0, 0.45, 0.08], ks: [0, 0, 0], ns: 1 },
	FlashCore: { kd: [1.0, 0.92, 0.65], ks: [0, 0, 0], ns: 1 },
});
const star = (material, z, outerRadius, innerRadius, points) => {
	for (let i = 0; i < points * 2; i++) {
		const radius = (i % 2 === 0) ? outerRadius : innerRadius;
		const nextRadius = (i % 2 === 0) ? innerRadius : outerRadius;
		const a0 = (i / (points * 2)) * Math.PI * 2;
		const a1 = ((i + 1) / (points * 2)) * Math.PI * 2;
		flash.doubleSided(material, [
			[0, 0, z],
			[Math.cos(a0) * radius, Math.sin(a0) * radius, z],
			[Math.cos(a1) * nextRadius, Math.sin(a1) * nextRadius, z],
		]);
	}
};
star('FlashOuter', 0.0, 0.075, 0.025, 7);
star('FlashCore', 0.004, 0.035, 0.014, 7);
for (let i = 0; i < 3; i++) {
	const a = (i / 3) * Math.PI + 0.3;
	const side = [Math.cos(a), Math.sin(a), 0];
	const at = (width, z) => [side[0] * width, side[1] * width, z];
	// 根元が太く先が細い炎の板です。
	flash.doubleSided('FlashOuter', [at(-0.035, 0), at(0.035, 0), at(0.012, 0.16), at(-0.012, 0.16)]);
	flash.doubleSided('FlashCore', [at(-0.015, 0.002), at(0.015, 0.002), at(0.004, 0.09), at(-0.004, 0.09)]);
}
flash.write('fpsMuzzleFlash');

