void KanjiText::SetText(const std::wstring& text)
{
	m_Indices.clear();
	for (wchar_t c : text)
	{
		if (c == L' ' || c == L'\u3000') // 半角/全角スペース
		{
			m_Indices.push_back(-1);
			continue;
		}

		auto it = m_CharTable.find(c);
		if (it != m_CharTable.end())
		{
			m_Indices.push_back(it->second);
		}
		else
		{
			// 常用漢字表にない文字(人名用漢字・表外字等)は空白扱い。
			m_Indices.push_back(-1);
		}
	}
}
